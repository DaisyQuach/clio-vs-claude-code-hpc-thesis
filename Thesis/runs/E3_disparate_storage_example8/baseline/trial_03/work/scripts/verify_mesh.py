"""Verify an Exodus II mesh against the locked E3-SPC-v1 §3 mesh settings. Usage: python3 -I verify_mesh.py mesh.exo out.txt"""
import sys, json, datetime
import numpy as np, netCDF4
exo = sys.argv[1]; out = sys.argv[2]
d = netCDF4.Dataset(exo)
def names(var):
    if var not in d.variables: return []
    v = d.variables[var]; v.set_auto_mask(False); arr = v[:]
    return [b''.join(bytes(c) if isinstance(c,(bytes,np.bytes_)) else (c.tobytes() if hasattr(c,'tobytes') else bytes(c)) for c in row).decode(errors='ignore').strip('\x00').strip() for row in arr]
res = {}; ok = True
def chk(key, got, exp):
    global ok
    good = (got == exp); ok &= bool(good)
    res[key] = {"expected": exp, "actual": got, "pass": bool(good)}
chk("num_dim", int(d.dimensions['num_dim'].size), 3)
chk("num_elem", int(d.dimensions['num_elem'].size), 13824)
chk("num_nodes", int(d.dimensions['num_nodes'].size), 15925)
chk("num_el_blk", int(d.dimensions['num_el_blk'].size), 1)
chk("num_node_sets", int(d.dimensions['num_node_sets'].size), 2)
chk("num_side_sets", int(d.dimensions['num_side_sets'].size), 1)
chk("block_names", names('eb_names'), ["block_1"])
chk("elem_type_block_1", d.variables['connect1'].elem_type.strip().upper(), "HEX8")
chk("block_1_elems", int(d.dimensions['num_el_in_blk1'].size), 13824)
x = d.variables['coordx'][:]; y = d.variables['coordy'][:]; z = d.variables['coordz'][:]
bb = [round(float(v),7) for v in (x.min(), x.max(), y.min(), y.max(), z.min(), z.max())]
chk("bounding_box_xmin_xmax_ymin_ymax_zmin_zmax", bb, [0.0, 2.0, 0.0, 1.0, 0.0, 0.5])
# uniform spacing: unique coordinates per axis
nx, ny, nz = len(np.unique(np.round(x,6))), len(np.unique(np.round(y,6))), len(np.unique(np.round(z,6)))
chk("nodes_per_axis_x_y_z", [nx,ny,nz], [49,25,13])
hs = [round(float(np.diff(np.unique(np.round(a,6))).mean()),6) for a in (x,y,z)]
chk("mean_element_size_x_y_z", hs, [round(1/24,6)]*3)
hmax = max(float(np.diff(np.unique(np.round(a,6))).max()) for a in (x,y,z)); hmin = min(float(np.diff(np.unique(np.round(a,6))).min()) for a in (x,y,z))
chk("element_size_uniform_within_1e-5", bool(hmax-hmin < 1e-5), True)
ns = names('ns_names'); ss = names('ss_names')
nsid = {n:i+1 for i,n in enumerate(ns)}; ssid = {n:i+1 for i,n in enumerate(ss)}
chk("nodeset_names", sorted(ns), ["ns_fix","ns_load"])
chk("sideset_names", ss, ["ss_sym"])
fix = d.variables['node_ns%d'%nsid['ns_fix']][:]-1; load = d.variables['node_ns%d'%nsid['ns_load']][:]-1
chk("ns_fix_count", int(len(fix)), 325)
chk("ns_fix_all_on_x0", bool(np.abs(x[fix]).max() < 1e-6), True)
chk("ns_fix_covers_all_x0_nodes", int((np.abs(x) < 1e-6).sum()), int(len(fix)))
chk("ns_load_count", int(len(load)), 13)
chk("ns_load_all_on_edge_x2_y0", bool(np.abs(x[load]-2.0).max() < 1e-6 and np.abs(y[load]).max() < 1e-6), True)
chk("ns_load_z_span", [round(float(z[load].min()),6), round(float(z[load].max()),6)], [0.0, 0.5])
chk("ns_load_covers_all_edge_nodes", int(((np.abs(x-2.0)<1e-6)&(np.abs(y)<1e-6)).sum()), int(len(load)))
se = d.variables['elem_ss%d'%ssid['ss_sym']][:]-1; sf = d.variables['side_ss%d'%ssid['ss_sym']][:]
chk("ss_sym_face_count", int(len(se)), 1152)
conn = d.variables['connect1'][:]-1
# Exodus HEX8 local side -> nodes
sides = {1:[0,1,5,4],2:[1,2,6,5],3:[2,3,7,6],4:[0,4,7,3],5:[0,3,2,1],6:[4,5,6,7]}
allz = True
for e,s in zip(se,sf):
    nd = conn[e][sides[int(s)]]
    if np.abs(z[nd]-0.5).max() > 1e-6: allz = False; break
chk("ss_sym_all_faces_on_z0.5", allz, True)
chk("ss_sym_unique_elements", int(len(np.unique(se))), 1152)
chk("ss_sym_nodes_count_(49x25)", int(len(np.unique(conn[se][:, :].ravel()[np.abs(z[conn[se].ravel()]-0.5)<1e-6]))), 1225)
res["_summary"] = {"file": exo, "utc": datetime.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ'), "all_pass": bool(ok), "exodus_api_version": str(getattr(d,'api_version','')), "title": str(getattr(d,'title',''))}
with open(out,'w') as f:
    f.write("# Mesh verification record (E3-SPC-v1 §3) -- generated by work/scripts/verify_mesh.py\n")
    f.write(json.dumps(res, indent=2)); f.write("\n")
print(json.dumps(res, indent=2)); print("ALL_PASS" if ok else "FAIL"); sys.exit(0 if ok else 1)
